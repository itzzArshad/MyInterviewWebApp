-- Phase 1: owner account + daily activity (streak / heatmap).
-- Kept portable between PostgreSQL (prod) and H2 in PostgreSQL mode (dev/tests).

CREATE TABLE app_user (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username       VARCHAR(64)  NOT NULL UNIQUE,
    password_hash  VARCHAR(100) NOT NULL,
    display_name   VARCHAR(100),
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    last_login_at  TIMESTAMP WITH TIME ZONE
);

CREATE TABLE activity_log (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT  NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    activity_date    DATE    NOT NULL,
    minutes          INT     NOT NULL DEFAULT 0,
    items_completed  INT     NOT NULL DEFAULT 0,
    CONSTRAINT uq_activity_user_date UNIQUE (user_id, activity_date)
);
