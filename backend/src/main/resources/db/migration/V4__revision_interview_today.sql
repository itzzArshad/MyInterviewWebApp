-- Revision (spaced repetition), mistake journal, interview bank, explain practice, mock interviews,
-- and daily training sessions.

ALTER TABLE quiz_question ADD COLUMN key_points_json VARCHAR(10000);
ALTER TABLE quiz_attempt ADD COLUMN mode VARCHAR(20) NOT NULL DEFAULT 'LESSON';      -- LESSON | RETRY | DRILL
ALTER TABLE activity_log ADD COLUMN session_completed BOOLEAN NOT NULL DEFAULT FALSE;

-- Interview Q&A extracted from each lesson's interview section
CREATE TABLE interview_item (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    concept_id       BIGINT NOT NULL REFERENCES concept (id),
    item_key         VARCHAR(20) NOT NULL,
    question_md      VARCHAR(5000) NOT NULL,
    answer_md        VARCHAR(50000) NOT NULL,
    key_points_json  VARCHAR(10000),
    follow_ups_json  VARCHAR(20000),
    sort_order       INT NOT NULL DEFAULT 0,
    active           BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_interview_item UNIQUE (concept_id, item_key)
);

-- One spaced-repetition card per thing to remember (SM-2 scheduling state)
CREATE TABLE review_card (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            BIGINT NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    card_type          VARCHAR(20) NOT NULL,     -- QUIZ | EXPLAIN | INTERVIEW
    source_key         VARCHAR(50) NOT NULL,     -- Q:<question id> | E:<concept id> | I:<interview item id>
    concept_id         BIGINT NOT NULL REFERENCES concept (id),
    question_id        BIGINT REFERENCES quiz_question (id),
    interview_item_id  BIGINT REFERENCES interview_item (id),
    ease               DOUBLE PRECISION NOT NULL DEFAULT 2.5,
    interval_days      INT NOT NULL DEFAULT 0,
    repetitions        INT NOT NULL DEFAULT 0,
    lapses             INT NOT NULL DEFAULT 0,
    due_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    last_reviewed_at   TIMESTAMP WITH TIME ZONE,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_review_card UNIQUE (user_id, source_key)
);
CREATE INDEX idx_review_card_due ON review_card (user_id, due_at);
CREATE INDEX idx_review_card_concept ON review_card (user_id, concept_id);

CREATE TABLE review_log (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id        BIGINT NOT NULL REFERENCES review_card (id) ON DELETE CASCADE,
    user_id        BIGINT NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    grade          INT NOT NULL,                 -- 1 Again, 2 Hard, 3 Good, 4 Easy
    interval_days  INT NOT NULL,                 -- interval after this review
    reviewed_at    TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_review_log_user_time ON review_log (user_id, reviewed_at);

-- Mistake journal: one row per question you have got wrong
CREATE TABLE mistake (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    question_id    BIGINT NOT NULL REFERENCES quiz_question (id),
    concept_id     BIGINT NOT NULL REFERENCES concept (id),
    given_answer   VARCHAR(20000),
    times          INT NOT NULL DEFAULT 1,
    note           VARCHAR(2000),
    resolved       BOOLEAN NOT NULL DEFAULT FALSE,
    last_wrong_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_mistake UNIQUE (user_id, question_id)
);

CREATE TABLE mock_session (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    plan_json    VARCHAR(20000) NOT NULL,        -- ordered questions with time limits
    started_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at  TIMESTAMP WITH TIME ZONE,
    score_pct    INT
);

-- Every spoken/explained answer (explain practice and mock interviews)
CREATE TABLE interview_answer (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    mock_session_id  BIGINT REFERENCES mock_session (id) ON DELETE CASCADE,
    mode             VARCHAR(10) NOT NULL,       -- EXPLAIN | MOCK
    source           VARCHAR(10) NOT NULL,       -- QA (interview item) | QUIZ (quiz question)
    item_id          BIGINT NOT NULL,
    concept_id       BIGINT NOT NULL REFERENCES concept (id),
    duration_sec     INT NOT NULL,
    points_total     INT NOT NULL,
    points_covered   INT NOT NULL,
    score_pct        INT NOT NULL,
    follow_up_ok     BOOLEAN,
    note             VARCHAR(5000),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_interview_answer_user_time ON interview_answer (user_id, created_at);

-- Backfill from existing history so revision starts with what you have already studied
INSERT INTO review_card (user_id, card_type, source_key, concept_id, question_id, due_at, created_at)
SELECT a.user_id, 'QUIZ', 'Q:' || ans.question_id, MIN(q.concept_id), ans.question_id, now(), now()
FROM quiz_answer ans
JOIN quiz_attempt a ON a.id = ans.attempt_id
JOIN quiz_question q ON q.id = ans.question_id
GROUP BY a.user_id, ans.question_id;

INSERT INTO review_card (user_id, card_type, source_key, concept_id, due_at, created_at)
SELECT p.user_id, 'EXPLAIN', 'E:' || p.concept_id, p.concept_id, now(), now()
FROM concept_progress p
WHERE p.status = 'COMPLETED';

INSERT INTO mistake (user_id, question_id, concept_id, given_answer, times, resolved, last_wrong_at, created_at)
SELECT a.user_id, ans.question_id, MIN(q.concept_id), MAX(ans.given_answer), COUNT(*), FALSE, MAX(ans.answered_at), MIN(ans.answered_at)
FROM quiz_answer ans
JOIN quiz_attempt a ON a.id = ans.attempt_id
JOIN quiz_question q ON q.id = ans.question_id
WHERE ans.is_correct = FALSE
GROUP BY a.user_id, ans.question_id;
