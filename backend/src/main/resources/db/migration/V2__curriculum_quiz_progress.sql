-- Phase 2: curriculum hierarchy, quiz engine, learning progress.
-- Large text uses VARCHAR(1000000): valid in PostgreSQL and H2, and maps cleanly to Java String.

CREATE TABLE learning_path (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug         VARCHAR(100) NOT NULL UNIQUE,
    title        VARCHAR(200) NOT NULL,
    description  VARCHAR(2000),
    sort_order   INT NOT NULL DEFAULT 0
);

CREATE TABLE subject (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    path_id      BIGINT NOT NULL REFERENCES learning_path (id),
    slug         VARCHAR(100) NOT NULL UNIQUE,
    title        VARCHAR(200) NOT NULL,
    description  VARCHAR(2000),
    sort_order   INT NOT NULL DEFAULT 0
);

CREATE TABLE chapter (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id   BIGINT NOT NULL REFERENCES subject (id),
    slug         VARCHAR(100) NOT NULL,
    title        VARCHAR(200) NOT NULL,
    sort_order   INT NOT NULL DEFAULT 0,
    CONSTRAINT uq_chapter_subject_slug UNIQUE (subject_id, slug)
);

CREATE TABLE concept (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chapter_id     BIGINT NOT NULL REFERENCES chapter (id),
    slug           VARCHAR(150) NOT NULL UNIQUE,
    title          VARCHAR(200) NOT NULL,
    difficulty     VARCHAR(20)  NOT NULL DEFAULT 'BEGINNER',
    status         VARCHAR(20)  NOT NULL DEFAULT 'PLANNED',   -- PUBLISHED | PLANNED | ARCHIVED
    summary        VARCHAR(2000),
    body_md        VARCHAR(1000000),
    related_slugs  VARCHAR(2000),
    est_minutes    INT NOT NULL DEFAULT 0,
    content_hash   VARCHAR(64),
    sort_order     INT NOT NULL DEFAULT 0,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_concept_chapter ON concept (chapter_id);

CREATE TABLE quiz_question (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    concept_id      BIGINT NOT NULL REFERENCES concept (id),
    question_key    VARCHAR(50)  NOT NULL,
    type            VARCHAR(30)  NOT NULL,
    difficulty      VARCHAR(20)  NOT NULL,
    prompt_md       VARCHAR(20000) NOT NULL,
    code_snippet    VARCHAR(20000),
    options_json    VARCHAR(20000),
    correct_answer  VARCHAR(5000),          -- NULL for self-graded questions
    explanation_md  VARCHAR(50000) NOT NULL,
    hints_json      VARCHAR(10000),
    sort_order      INT NOT NULL DEFAULT 0,
    active          BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_question_concept_key UNIQUE (concept_id, question_key)
);
CREATE INDEX idx_question_concept ON quiz_question (concept_id);

CREATE TABLE concept_progress (
    user_id         BIGINT NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    concept_id      BIGINT NOT NULL REFERENCES concept (id),
    status          VARCHAR(20) NOT NULL DEFAULT 'NOT_STARTED',  -- NOT_STARTED | IN_PROGRESS | COMPLETED
    mastery         INT NOT NULL DEFAULT 0,                      -- 0..100
    bookmarked      BOOLEAN NOT NULL DEFAULT FALSE,
    last_viewed_at  TIMESTAMP WITH TIME ZONE,
    completed_at    TIMESTAMP WITH TIME ZONE,
    PRIMARY KEY (user_id, concept_id)
);
CREATE INDEX idx_progress_user_status ON concept_progress (user_id, status);

CREATE TABLE quiz_attempt (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    concept_id    BIGINT NOT NULL REFERENCES concept (id),
    question_ids  VARCHAR(4000) NOT NULL,   -- ordered, comma separated
    started_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at   TIMESTAMP WITH TIME ZONE,
    score         INT,
    total         INT NOT NULL
);
CREATE INDEX idx_attempt_user_concept ON quiz_attempt (user_id, concept_id);

CREATE TABLE quiz_answer (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id    BIGINT NOT NULL REFERENCES quiz_attempt (id) ON DELETE CASCADE,
    question_id   BIGINT NOT NULL REFERENCES quiz_question (id),
    given_answer  VARCHAR(20000),
    is_correct    BOOLEAN NOT NULL,
    hints_used    INT NOT NULL DEFAULT 0,
    answered_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_answer_attempt_question UNIQUE (attempt_id, question_id)
);
